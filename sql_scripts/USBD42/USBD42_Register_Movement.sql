SET SERVEROUTPUT ON;

    -- As a Freight Manager, I want to register a train movement in the database.
    -- If the train stopped at the facility, the departure time shall also be registered

CREATE TABLE Train_Movement (
movementID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
trainID NUMBER,
facilityID NUMBER,
arrivalTime TIMESTAMP,
departureTime TIMESTAMP
);
/

CREATE OR REPLACE FUNCTION fn_usbd42(
    p_train_id IN NUMBER,
    p_facility_id IN NUMBER,
    p_arrival IN TIMESTAMP,
    p_departure IN TIMESTAMP
) RETURN BOOLEAN IS
BEGIN
INSERT INTO Train_Movement (trainID, facilityID, arrivalTime, departureTime)
VALUES (p_train_id, p_facility_id, p_arrival, p_departure);

RETURN TRUE;

EXCEPTION
    WHEN OTHERS THEN
        RETURN FALSE;
END fn_usbd42;
/